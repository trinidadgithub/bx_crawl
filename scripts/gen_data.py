#!/usr/bin/env python3
"""
BX Data Codegen
Reads dnd-data/schemas/ and dnd-data/data/ JSON files,
emits include/bx_data.hpp with constexpr C++20 tables.
"""

import json, os, re, sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SCHEMAS = REPO / "dnd-data" / "schemas"
DATA = REPO / "dnd-data" / "data"
OUTPUT = REPO / "include" / "bx_data.hpp"

def read_json(path):
    with open(path) as f:
        return json.load(f)

def read_data(filename):
    return read_json(DATA / filename)

def read_schema(filename):
    return read_json(SCHEMAS / filename)

H = []

def emit(line=""):
    H.append(line)

def emit_block(lines):
    H.extend(lines)

def cpp_str(s):
    """Convert a Python string to a valid C++ string literal."""
    if not isinstance(s, str):
        return str(s)
    # Escape backslash first, then double quotes, then control chars
    escaped = s.replace("\\", "\\\\").replace('"', '\\"')
    # Replace newlines, tabs, etc
    escaped = escaped.replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
    return f'"{escaped}"'

def cpp_val(v):
    """Format a Python value as a C++ literal."""
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, str):
        return cpp_str(v)
    if v is None:
        return "0"  # null -> 0 for our struct defaults
    return str(v)

def cpp_ident(s):
    """Convert a string to a valid C++ identifier."""
    ident = s.replace("-", "_").replace(" ", "_").replace(".", "_").replace("'", "")
    # Remove leading digits if any
    ident = re.sub(r'^\d+', '', ident)
    if not ident:
        ident = "unnamed"
    return ident

def cpp_enum_ident(s):
    """Convert to a valid C++ enum value identifier."""
    return cpp_ident(s)

# ============================================================
# START HEADER
# ============================================================
emit_block([
    "#ifndef BX_DATA_HPP",
    "#define BX_DATA_HPP",
    "",
    "#include <array>",
    "#include <cstdint>",
    "",
    "// Auto-generated by scripts/gen_data.py -- do not edit by hand",
    "// Sources: dnd-data/schemas/*.json, dnd-data/data/*.json",
    "",
    "namespace bx {",
    "",
])

# ============================================================
# 1. ABILITY SCORES
# ============================================================
emit("// ========== Ability Score Modifiers ==========")
emit("")

schema_abilities = read_schema("01-ability-scores.json")

for a in schema_abilities["scores"]:
    aid = a["id"]
    adj = a["adjustments"]
    fields = [k for k in adj[0].keys() if k != "range"]

    field_types = []
    for f in fields:
        v = adj[0][f]
        if isinstance(v, bool):
            field_types.append((f, "bool"))
        elif isinstance(v, int):
            field_types.append((f, "int"))
        else:
            field_types.append((f, "const char*"))

    struct_name = aid.capitalize() + "Mods"
    emit(f"struct {struct_name} {{")
    for fname, ftype in field_types:
        emit(f"    {ftype} {fname};")
    emit("};")
    emit("")

    array_name = aid + "_mods"
    emit(f"inline constexpr std::array<{struct_name}, 7> {array_name}{{{{")
    for band in adj:
        vals = ", ".join(cpp_val(band[f]) for f, _ in field_types)
        emit(f"    {{ {vals} }},")
    emit("}};")
    emit("")

emit("inline constexpr int score_band(int score) noexcept {")
emit("    if (score <= 3) return 0;")
emit("    if (score <= 5) return 1;")
emit("    if (score <= 8) return 2;")
emit("    if (score <= 12) return 3;")
emit("    if (score <= 15) return 4;")
emit("    if (score <= 17) return 5;")
emit("    return 6;")
emit("}")
emit("")

for a in schema_abilities["scores"]:
    aid = a["id"]
    struct_name = aid.capitalize() + "Mods"
    array_name = aid + "_mods"
    emit(f"inline constexpr const {struct_name}& get_{aid}(int score) noexcept {{")
    emit(f"    return {array_name}[score_band(score)];")
    emit("}")
    emit("")

# ============================================================
# 2. CHARACTER CLASSES
# ============================================================
emit("// ========== Character Classes ==========")
emit("")

schema_classes = read_schema("02-character-classes.json")

emit("enum class ClassId {")
for cls in schema_classes["classes"]:
    emit(f"    {cpp_ident(cls['id'])},")
emit("};")
emit("")

emit("struct ClassInfo {")
emit("    const char* id;")
emit("    const char* name;")
emit("    const char* prime_requisite;")
emit("    const char* hit_die;")
emit("    const char* saves_as;")
emit("    bool allowed_armor_any;")
emit("    bool allowed_shield;")
emit("    const char* allowed_weapons;")
emit("};")
emit("")

emit("inline constexpr ClassInfo class_info[] = {")
for cls in schema_classes["classes"]:
    armor = "true" if cls.get("allowedArmor") == ["any"] else "false"
    shield = "true" if cls.get("allowedShield") else "false"
    weapons = ", ".join(cls.get("allowedWeapons", []))
    emit(f'    {{ {cpp_str(cls["id"])}, {cpp_str(cls["name"])}, {cpp_str(cls["primeRequisite"])}, '
         f'{cpp_str(cls["hitDie"])}, {cpp_str(cls["savesAs"])}, '
         f'{armor}, {shield}, {cpp_str(weapons)} }},')
emit("};")
emit("")

emit("struct ClassLevel {")
emit("    int level;")
emit("    const char* title;")
emit("    int xp_required;")
emit("    const char* hit_dice;")
emit("    int first_level_spells;")
emit("    int second_level_spells;")
emit("};")
emit("")

for cls in schema_classes["classes"]:
    cid = cpp_ident(cls["id"])
    levels = cls["levels"]
    emit(f"inline constexpr std::array<ClassLevel, {len(levels)}> {cid}_levels{{{{")
    for lv in levels:
        spells = lv.get("spells", {})
        fs = spells.get("first", 0)
        ss = spells.get("second", 0)
        emit(f'    {{ {lv["level"]}, {cpp_str(lv["title"])}, {lv["xpRequired"]}, {cpp_str(lv["hitDice"])}, {fs}, {ss} }},')
    emit("}};")
    emit("")

# ============================================================
# 3. SPELLS
# ============================================================
emit("// ========== Spells ==========")
emit("")

data_spells = read_data("spells.json")

all_spells = []
for category, spell_list in data_spells.items():
    for s in spell_list:
        all_spells.append(s)

emit("struct Spell {")
emit("    const char* name;")
emit("    int level;")
emit("    const char* class_name;")
emit("};")
emit("")

emit(f"inline constexpr std::array<Spell, {len(all_spells)}> spells{{{{")
for s in all_spells:
    emit(f'    {{ {cpp_str(s["name"])}, {s["level"]}, {cpp_str(s["class"])} }},')
emit("}};")
emit("")

# ============================================================
# 4. EQUIPMENT
# ============================================================
emit("// ========== Equipment ==========")
emit("")

schema_equip = read_schema("04-equipment.json")

weapons_list = schema_equip["weapons"]
emit("struct Weapon {")
emit("    const char* id;")
emit("    const char* name;")
emit("    int cost_gp;")
emit("    const char* damage_die;")
emit("    bool two_handed;")
emit("    bool cleric_allowed;")
emit("    bool thrown;")
emit("};")
emit("")

emit(f"inline constexpr std::array<Weapon, {len(weapons_list)}> weapons{{{{")
for w in weapons_list:
    emit(f'    {{ {cpp_str(w["id"])}, {cpp_str(w["name"])}, {w["costGp"]}, {cpp_str(w["damageDie"])}, '
         f'{"true" if w.get("twoHanded") else "false"}, '
         f'{"true" if w.get("clericAllowed") else "false"}, '
         f'{"true" if w.get("thrown") else "false"} }},')
emit("}};")
emit("")

armor_list = schema_equip["armor"]
emit("struct ArmorItem {")
emit("    const char* id;")
emit("    const char* name;")
emit("    int cost_gp;")
emit("    int ac;")
emit("    const char* armor_type;")
emit("};")
emit("")

emit(f"inline constexpr std::array<ArmorItem, {len(armor_list)}> armor_items{{{{")
for a in armor_list:
    emit(f'    {{ {cpp_str(a["id"])}, {cpp_str(a["name"])}, {a["costGp"]}, {a["ac"]}, {cpp_str(a.get("type", ""))} }},')
emit("}};")
emit("")

gear_list = schema_equip["gear"]
emit("struct GearItem {")
emit("    const char* id;")
emit("    const char* name;")
emit("    int cost_gp;")
emit("};")
emit("")

emit(f"inline constexpr std::array<GearItem, {len(gear_list)}> gear_items{{{{")
for g in gear_list:
    emit(f'    {{ {cpp_str(g["id"])}, {cpp_str(g["name"])}, {g["costGp"]} }},')
emit("}};")
emit("")

# ============================================================
# 5. MONSTERS
# ============================================================
emit("// ========== Monsters ==========")
emit("")

data_monsters = read_data("monsters.json")

emit("struct Monster {")
emit("    const char* name;")
emit("    int ac;")
emit("    const char* hit_dice;")
emit("    const char* move;")
emit("    const char* attacks;")
emit("    const char* damage;")
emit("    const char* no_appearing;")
emit("    const char* saves_as;")
emit("    int morale;")
emit("    const char* treasure_type;")
emit("    const char* alignment;")
emit("};")
emit("")

emit(f"inline constexpr std::array<Monster, {len(data_monsters)}> monsters{{{{")
for m in data_monsters:
    mor = m.get("Morale", "0")
    if isinstance(mor, str):
        try:
            mor_int = int(mor)
        except ValueError:
            mor_int = 0
    else:
        mor_int = mor
    emit(f'    {{ {cpp_str(m.get("_name", ""))}, {m.get("Armor Class", 9)}, '
         f'{cpp_str(m.get("Hit Dice", ""))}, '
         f'{cpp_str(m.get("Move", ""))}, '
         f'{cpp_str(m.get("Attacks", ""))}, '
         f'{cpp_str(m.get("Damage", ""))}, '
         f'{cpp_str(m.get("No. Appearing", ""))}, '
         f'{cpp_str(m.get("Save As", ""))}, '
         f'{mor_int}, '
         f'{cpp_str(m.get("Treasure Type", ""))}, '
         f'{cpp_str(m.get("Alignment", ""))} }},')
emit("}};")
emit("")

# ============================================================
# 6. ATTACK TABLES
# ============================================================
emit("// ========== Attack Tables ==========")
emit("")

schema_attacks = read_schema("06-attack-tables.json")

emit("struct AttackRow {")
ac_cols = [9, 8, 7, 6, 5, 4, 3, 2, 1, 0, -1, -2, -3]
for ac in ac_cols:
    label = f"ac_{ac}" if ac >= 0 else f"ac_neg{abs(ac)}"
    emit(f"    int {label};")
emit("};")
emit("")

char_attacks = schema_attacks["characterAttacks"]
emit(f"inline constexpr std::array<AttackRow, {len(char_attacks)}> character_attack_table{{{{")
for row in char_attacks:
    vals = ", ".join(str(v) for v in row["toHitRow"])
    emit(f"    {{ {vals} }},")
emit("}};")
emit("")

mon_attacks = schema_attacks["monsterAttacks"]
emit(f"inline constexpr std::array<AttackRow, {len(mon_attacks)}> monster_attack_table{{{{")
for row in mon_attacks:
    vals = ", ".join(str(v) for v in row["toHitRow"])
    emit(f"    {{ {vals} }},")
emit("}};")
emit("")

emit("struct MonsterHDRange {")
emit("    int hd_min;")
emit("    int hd_max;")
emit("};")
emit("")

emit(f"inline constexpr std::array<MonsterHDRange, {len(mon_attacks)}> monster_hd_ranges{{{{")
for row in mon_attacks:
    hd = row["hdRange"]
    mn = hd.get("min", 0)
    mx = hd.get("max") if hd.get("max") is not None else 0
    def parse_hd(v):
        try:
            return int(v)
        except (ValueError, TypeError):
            if isinstance(v, str):
                parts = v.split("+")
                try:
                    return int(parts[0])
                except ValueError:
                    return 0
            return 0
    emit(f"    {{ {parse_hd(mn)}, {parse_hd(mx)} }},")
emit("}};")
emit("")

# ============================================================
# 7. SAVING THROWS
# ============================================================
emit("// ========== Saving Throws ==========")
emit("")

schema_saves = read_schema("07-saving-throws.json")

emit("struct SaveRow {")
emit("    int death_ray_poison;")
emit("    int magic_wands;")
emit("    int paralysis_petrify;")
emit("    int dragon_breath;")
emit("    int rods_spells;")
emit("};")
emit("")

save_rows = schema_saves["savingThrows"]
emit(f"inline constexpr std::array<SaveRow, {len(save_rows)}> saving_throws{{{{")
for s in save_rows:
    emit(f'    {{ {s["deathRayPoison"]}, {s["magicWands"]}, '
         f'{s["paralysisPetrify"]}, {s["dragonBreath"]}, '
         f'{s["spells"]} }},')
emit("}};")
emit("")

emit("enum class SaveClass {")
seen = set()
for s in save_rows:
    c = s["class"]
    if c not in seen:
        emit(f"    {c},")
        seen.add(c)
emit("};")
emit("")

# ============================================================
# 8. TREASURE TYPES
# ============================================================
emit("// ========== Treasure Types ==========")
emit("")

schema_treasure = read_schema("08-treasure-types.json")

emit("struct TreasureEntry {")
emit("    int chance_pct;")
emit("    const char* range_str;")
emit("    const char* unit;")
emit("};")
emit("")

emit("struct LairTreasure {")
emit("    const char* id;")
emit("    TreasureEntry copper;")
emit("    TreasureEntry silver;")
emit("    TreasureEntry electrum;")
emit("    TreasureEntry gold;")
emit("    TreasureEntry platinum;")
emit("    TreasureEntry gems;")
emit("    const char* magic_items;")
emit("    int avg_value_gp;")
emit("};")
emit("")

lair_types = schema_treasure.get("lairTypes", [])
emit(f"inline constexpr LairTreasure lair_treasure_types[] = {{")
for lt in lair_types:
    def_entry = lambda key: lt.get(key) or {"chancePct": 0, "range": "", "unit": ""}
    emit("    {")
    emit(f'        {cpp_str(lt["id"])},')
    for coin in ["copper", "silver", "electrum", "gold", "platinum"]:
        e = def_entry(coin)
        emit(f'        {{ {e["chancePct"]}, {cpp_str(e.get("range", ""))}, {cpp_str(e.get("unit", ""))} }},')
    gems = def_entry("gems")
    emit(f'        {{ {gems["chancePct"]}, {cpp_str(gems.get("range", ""))}, {cpp_str("")} }},')
    mi = lt.get("magicItems")
    emit(f'        {cpp_str(mi) if mi else cpp_str("")},')
    emit(f'        {lt.get("avgValueGp", 0)}')
    emit("    },")
emit("};")
emit("")

# ============================================================
# CLOSE
# ============================================================
emit("}  // namespace bx")
emit("")
emit("#endif  // BX_DATA_HPP")

OUTPUT.parent.mkdir(parents=True, exist_ok=True)
OUTPUT.write_text("\n".join(H) + "\n")

print(f"Generated {OUTPUT} ({len(H)} lines)")
